## maxcompute 有字符串01101110101，第一个数字代表2026年2月，第二个代表三月，如此类推。如何找出最后一个01的字符串里面的1代表的月份

SELECT 
    TRANSFORM(
        -- 1. 提取最后一个 "01" 之后的字符串，拆分并过滤出 '1'
        FILTER(
            SPLIT(REGEXP_EXTRACT('0110111010111', '.*01(*)$', 1), ''), 
            x -> x = '1'
        ),
        -- 2. 计算年份和月份（处理跨年）
        (x, i) -> STRUCT(
            2026 + (2 + i - 1) / 12 AS year,   -- 年份：基准年 + 总月份数整除12
            (2 + i - 1) % 12 + 1 AS month      -- 月份：总月份数对12取模（加1是因为取模结果是0-11）
        )
    ) AS year_month_list;
