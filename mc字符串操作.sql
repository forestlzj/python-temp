### 💡 逻辑逐步拆解（以跨年为例）

为了验证跨年逻辑，我们换一个更长的测试字符串：`'0110111010111'`。
假设最后一个 `01` 提取出的后缀是 `'0111'`（长度为4，索引 `i` 分别为 0, 1, 2, 3），基准是 2026年2月：

1. **索引 i = 0**（后缀第1位是1）：
   * 相对月份 = 2 + 0 = 2月
   * 年份 = 2026 + (2 - 1) / 12 = 2026 + 0 = **2026年**
   * 月份 = (2 - 1) % 12 + 1 = 1 + 1 = **2月**
2. **索引 i = 10**（假设后缀很长，第11位是1）：
   * 相对月份 = 2 + 10 = 12月
   * 年份 = 2026 + (12 - 1) / 12 = 2026 + 0 = **2026年**
   * 月份 = (12 - 1) % 12 + 1 = 11 + 1 = **12月**
3. **索引 i = 11**（后缀第12位是1，此时已跨年）：
   * 相对月份 = 2 + 11 = 13月
   * 年份 = 2026 + (13 - 1) / 12 = 2026 + 1 = **2027年**
   * 月份 = (13 - 1) % 12 + 1 = 0 + 1 = **1月**

### 🛠️ 进阶：输出格式化字符串

如果你希望直接得到像 `'2027-01'` 这样的字符串结果，可以在 `TRANSFORM` 里加上 `LPAD` 函数给月份补零，并用 `CONCAT` 拼接：

```sql
SELECT 
    TRANSFORM(
        FILTER(SPLIT(REGEXP_EXTRACT('0110111010111', '.*01(*)$', 1), ''), x -> x = '1'),
        (x, i) -> CONCAT(
            CAST(2026 + (2 + i - 1) / 12 AS STRING), 
            '-', 
            LPAD(CAST((2 + i - 1) % 12 + 1 AS STRING), 2, '0')
        )
    ) AS formatted_dates;
